using Radency.Rentals.Application.Common;
using Radency.Rentals.Domain.Applications;

namespace Radency.Rentals.Application.Applications;

public sealed record ApplicantInfoDto(string FullName, string Phone, string Email, string CurrentAddress);

public sealed record ResidenceDto(
    string Address,
    string LandlordName,
    string LandlordPhone,
    DateOnly MoveInDate,
    DateOnly MoveOutDate);

public sealed record UnitSummaryDto(
    Guid Id,
    string UnitNumber,
    int Bedrooms,
    decimal MonthlyRent,
    string UnitTypeName,
    Guid PropertyId,
    string PropertyName,
    string PropertyAddress);

public sealed record LeaseDto(Guid Id, DateOnly StartDate, DateOnly EndDate);

/// <summary>
/// The single view model that drives the application page. Permission flags are decided
/// on the server; the client only renders sections editable or read-only accordingly.
/// </summary>
public sealed record ApplicationDto(
    Guid Id,
    ApplicationStatus Status,
    UnitSummaryDto Unit,
    Guid ApplicantId,
    string ApplicantName,
    ApplicantInfoDto? ApplicantInfo,
    IReadOnlyList<ResidenceDto> Residences,
    bool ApplicantInfoCompleted,
    bool ResidenceHistoryCompleted,
    bool IsEditable,
    bool CanSubmit,
    bool CanWithdraw,
    bool CanReview,
    LeaseDto? Lease,
    string? LastReviewComment,
    DateTime CreatedAt,
    DateTime UpdatedAt,
    DateTime? SubmittedAt,
    Guid Version);

public sealed record ApplicationListItemDto(
    Guid Id,
    ApplicationStatus Status,
    Guid UnitId,
    string UnitNumber,
    Guid PropertyId,
    string PropertyName,
    string ApplicantName,
    decimal MonthlyRent,
    DateTime CreatedAt,
    DateTime? SubmittedAt,
    DateTime UpdatedAt);

public sealed record StatusChangeDto(
    Guid Id,
    ApplicationStatus? FromStatus,
    ApplicationStatus ToStatus,
    ReviewOutcome? Outcome,
    string? Comment,
    string ChangedBy,
    DateTime ChangedAt);

public sealed record ManagerNoteDto(string Text, string? UpdatedBy, DateTime? UpdatedAt, Guid? Version);

public enum ApplicationSortField
{
    UpdatedAt,
    CreatedAt,
    SubmittedAt,
    Status,
    Property,
    Applicant,
}

public sealed class ApplicationListQuery
{
    public ApplicationStatus? Status { get; init; }

    public Guid? PropertyId { get; init; }

    public int Page { get; init; } = 1;

    public int PageSize { get; init; } = 20;

    public ApplicationSortField SortBy { get; init; } = ApplicationSortField.UpdatedAt;

    public SortDirection SortDirection { get; init; } = SortDirection.Desc;
}

/// <summary>The id is generated by the client so a replayed offline request can't create a duplicate.</summary>
public sealed record CreateApplicationRequest(Guid Id, Guid UnitId);

public enum FormCommand
{
    /// <summary>Validate the posted section, persist it when valid, move on.</summary>
    Continue,

    /// <summary>Submit from the Summary (both sections must already be saved).</summary>
    Submit,
}

/// <summary>
/// The one form the application page posts. The command (the button that was pressed)
/// decides what the server does with it. "Back" never reaches the server: it doesn't save.
/// </summary>
public sealed record ApplicationFormRequest(
    FormCommand Command,
    ApplicationSection? Section,
    ApplicantInfoDto? ApplicantInfo,
    IReadOnlyList<ResidenceDto>? Residences,
    Guid Version);

public sealed record WithdrawApplicationRequest(Guid Version);

public sealed record ReviewApplicationRequest(ReviewOutcome Outcome, string? Comment, Guid Version);

public sealed record UpdateManagerNoteRequest(string Text, Guid? Version);

/// <summary>Validation wrapper so residence errors are keyed as "residences[i].field".</summary>
public sealed record ResidenceHistoryInput(IReadOnlyList<ResidenceDto> Residences);
