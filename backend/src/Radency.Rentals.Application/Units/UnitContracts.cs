namespace Radency.Rentals.Application.Units;

public sealed record UnitDto(
    Guid Id,
    Guid PropertyId,
    string UnitNumber,
    int Bedrooms,
    decimal MonthlyRent,
    int UnitTypeId,
    string UnitTypeName,
    bool UnitTypeIsActive,
    bool IsAvailable,
    DateOnly? LeasedUntil,
    Guid Version);

public sealed record AvailableUnitDto(
    Guid Id,
    Guid PropertyId,
    string PropertyName,
    string PropertyAddress,
    string City,
    string UnitNumber,
    int Bedrooms,
    decimal MonthlyRent,
    string UnitTypeName);

public sealed record UnitTypeDto(int Id, string Name, bool IsActive);

/// <summary>The id is generated by the client so a replayed offline request can't create a duplicate.</summary>
public sealed record CreateUnitRequest(Guid Id, string UnitNumber, int Bedrooms, decimal MonthlyRent, int UnitTypeId);

public sealed record UpdateUnitRequest(string UnitNumber, int Bedrooms, decimal MonthlyRent, int UnitTypeId, Guid Version);
